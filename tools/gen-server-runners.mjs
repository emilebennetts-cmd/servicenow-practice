// Generates a server-side, ID-only allowlist from the exact scripts bundled
// into the Workbench UI. The REST API never accepts executable source.
import { readFileSync, writeFileSync, mkdirSync } from 'fs'
import { gunzipSync } from 'zlib'
import { dirname, join } from 'path'
import { fileURLToPath } from 'url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const bundle = readFileSync(join(root, 'src/bundle/workbench.js'), 'utf8')
const match = bundle.match(/const WORKBENCH_SCRIPT_SOURCES_GZIP = "([^"]+)"/)
if (!match) throw new Error('The bundled Workbench script registry was not found.')

const sources = JSON.parse(gunzipSync(Buffer.from(match[1], 'base64')).toString('utf8'))
const writeIds = new Set(['FIX-02', 'FIX-03', 'FIX-04', 'FIX-06', 'FIX-09', 'FIX-17'])

function safeFunctionName(id) {
  return `run_${id.replace(/[^A-Za-z0-9_]/g, '_')}`
}

function transformSource(id, input) {
  let source = String(input)
    // The profile comes from typed, server-sanitised fields only.
    .replace(/var CUSTOMER_PROFILE = \{[\s\S]*?\};/, 'var CUSTOMER_PROFILE = __profile;')
    // A server route may never turn an approval-gated template into APPLY.
    .replace(/runMode\s*:\s*["']APPLY["']/g, 'runMode: "PLAN"')
    // Capture output without writing one attachment for every script in a phase.
    .replace(/gs\.(?:print|info|error)\(/g, '__capture(')
    .replace(/(?:new GlideSysAttachment\(\)|attachment)\.write\((?:currentUser|user),\s*(fileName|name),\s*["']application\/json["'],\s*json\)/g,
      (_whole, name) => `(__attachmentJson = json, __attachmentName = String(${name}), "virtual")`)
    // This global-only helper is unavailable to scoped modules. Direct-class
    // coverage is still reported; inherited-rule traversal is left applicable.
    .replace('var chain = GlideDBObjectManager.get().getTables(className);',
      'var chain = { size: function () { return 1; }, get: function () { return className; } };')

  const configHook = `
  if (typeof CONFIGURATION !== "undefined" && CONFIGURATION.targets) {
    for (var __targetIndex = 0; __targetIndex < CONFIGURATION.targets.length; __targetIndex += 1) {
      var __target = CONFIGURATION.targets[__targetIndex];
      if (__target && __target.query) __target.query = __replaceProfileTokens(__target.query, __profile);
    }
  }
  var result = {`
  source = source.replace(/\n\s*var result = \{/, configHook)

  return `
function ${safeFunctionName(id)}(__profile: any) {
  var __captured: string[] = []
  var __attachmentJson = ''
  var __attachmentName = ''
  function __capture(value: any) { __captured.push(String(value === undefined ? '' : value)) }
${source}
  return __runnerResult(${JSON.stringify(id)}, __captured, __attachmentJson, __attachmentName, ${writeIds.has(id)})
}
`
}

const ids = Object.keys(sources).sort()
const functions = ids.map((id) => transformSource(id, sources[id])).join('\n')
const cases = ids.map((id) => `    case ${JSON.stringify(id)}: return ${safeFunctionName(id)}(profile)`).join('\n')

const output = `// Generated by tools/gen-server-runners.mjs. Do not edit directly.
// @ts-nocheck
import { gs, GlideAggregate, GlideDateTime, GlideRecord, GlideSysAttachment } from '@servicenow/glide'

export const WORKBENCH_SCRIPT_IDS = ${JSON.stringify(ids)}

function __replaceProfileTokens(value: any, profile: any) {
  var scopes = Array.isArray(profile.scopes) ? profile.scopes.join(',') : ''
  var prefixes = Array.isArray(profile.tablePrefixes) ? profile.tablePrefixes : []
  return String(value || '')
    .replace(/CUSTOMER_SCOPES/g, scopes)
    .replace(/CUSTOMER_SCOPE/g, scopes.split(',')[0] || 'CUSTOMER_SCOPE')
    .replace(/CUSTOMER_TABLE_PREFIX/g, prefixes[0] || 'CUSTOMER_TABLE_PREFIX')
}

function __runnerResult(scriptId: string, captured: string[], attachmentJson: string, attachmentName: string, planOnly: boolean) {
  var raw = attachmentJson || captured.join('\\n')
  var payload: any = null
  try {
    if (attachmentJson) payload = JSON.parse(attachmentJson)
    else {
      var start = raw.indexOf('DIAG_ENVELOPE_BEGIN')
      var end = raw.indexOf('DIAG_ENVELOPE_END', start + 19)
      if (start >= 0 && end > start) {
        var slice = raw.substring(start + 19, end)
        payload = JSON.parse(slice.substring(slice.indexOf('{'), slice.lastIndexOf('}') + 1))
      } else {
        var first = raw.indexOf('{')
        var last = raw.lastIndexOf('}')
        if (first >= 0 && last > first) payload = JSON.parse(raw.substring(first, last + 1))
      }
    }
  } catch (parseError) {
    payload = null
  }
  if (!payload) payload = {
    schema: 'servicenow-diagnostic-result/1', scriptId: scriptId,
    mode: planOnly ? 'PLAN' : 'READ_ONLY', ok: false, records: [], counts: {},
    warnings: [], errors: ['The collector completed without a parseable output envelope.'], raw: raw.substring(0, 20000)
  }
  return { scriptId: scriptId, planOnly: planOnly, payload: payload, outputName: attachmentName, captured: captured.slice(-8) }
}

${functions}

export function executeWhitelistedScript(scriptId: string, profile: any) {
  switch (scriptId) {
${cases}
    default: throw new Error('Script is not in the Workbench allowlist: ' + scriptId)
  }
}
`

const destination = join(root, 'src/server/generated-runners.ts')
mkdirSync(dirname(destination), { recursive: true })
writeFileSync(destination, output)
console.log(`generated-runners.ts written: ${ids.length} allowlisted scripts, ${output.length.toLocaleString()} characters`)
